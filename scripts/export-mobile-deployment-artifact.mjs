import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const artifactPath = resolve(root, 'contracts/out/CreatorAdvance.sol/CreatorAdvance.json');
const destination = resolve(root, 'apps/mobile/src/lib/creator-advance-deploy-artifact.ts');
const artifact = JSON.parse(await readFile(artifactPath, 'utf8'));
const constructor = artifact.abi.find((item) => item.type === 'constructor');
if (!constructor || constructor.inputs.map((input) => input.type).join(',') !== 'address,address,address') {
  throw new Error('CreatorAdvance constructor ABI changed; review the mobile deployment form before updating it.');
}
const rawBytecode = artifact.bytecode?.object;
const bytecode = typeof rawBytecode === 'string' ? rawBytecode.replace(/^0x/i, '') : '';
if (!bytecode || !/^[0-9a-f]+$/i.test(bytecode)) throw new Error('Foundry artifact has no valid deployment bytecode.');

const output = [
  '// Generated by scripts/export-mobile-deployment-artifact.mjs after `forge build`. Do not edit by hand.',
  `export const creatorAdvanceDeployAbi = ${JSON.stringify([constructor])} as const;`,
  `export const creatorAdvanceDeploymentBytecode = '0x${bytecode}' as const;`,
  '',
].join('\n');
await writeFile(destination, output);
process.stdout.write(`Wrote ${destination.replace(root, '.')}; bytecode ${bytecode.length / 2} bytes.\n`);
